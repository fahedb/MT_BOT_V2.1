/*
    Creates the BackTest_DirectionStats table.

    Purpose:
    Stores direction-vote statistics generated during C++ backtest simulations.
    Each row represents the aggregated directional statistics for a specific
    simulation, vote type, and time point.

    Notes:
    - The primary key is composed of SimulationID, VoteType, and TimePoint.
    - No foreign keys were defined in the source database export.
    - No production data is included.
*/

IF OBJECT_ID(N'dbo.BackTest_DirectionStats', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BackTest_DirectionStats
    (
        SimulationID INT NOT NULL,
        TimePoint BIGINT NOT NULL,
        CoinsPair NVARCHAR(8) NOT NULL,
        VoteType NVARCHAR(10) NOT NULL,

        TotalVotes INT NOT NULL,

        UpPercentage DECIMAL(18, 8) NOT NULL,
        DownPercentage DECIMAL(18, 8) NOT NULL,
        BlurPercentage DECIMAL(18, 8) NOT NULL,

        Mean DECIMAL(18, 8) NOT NULL,
        PureMean_Up DECIMAL(18, 8) NOT NULL,
        PureMean_Down DECIMAL(18, 8) NOT NULL,
        StdDev DECIMAL(18, 8) NOT NULL,
        MeanIndexes DECIMAL(18, 8) NOT NULL,

        TradeResult INT NOT NULL,

        CONSTRAINT PK_BackTest_DirectionStats
            PRIMARY KEY CLUSTERED
            (
                SimulationID ASC,
                VoteType ASC,
                TimePoint ASC
            )
    );
END;
GO
