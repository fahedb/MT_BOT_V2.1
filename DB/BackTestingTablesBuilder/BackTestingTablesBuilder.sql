/*
    Creates the BackTest_AccountStateEvents table.

    Purpose:
    Stores account state snapshots during C++ backtest simulations.
    Each row represents the account state at a specific simulation time point,
    including balance, equity, margin usage, floating PnL, and current profit.

    Notes:
    - The primary key is composed of SimulationID and CurrTimePoint.
    - No foreign keys were defined in the source database export.
    - No production data is included.
*/

IF OBJECT_ID(N'dbo.BackTest_AccountStateEvents', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BackTest_AccountStateEvents
    (
        SimulationID INT NOT NULL,
        CurrTimePoint BIGINT NOT NULL,

        AccountBalance DECIMAL(18, 8) NOT NULL,
        EquityBalance DECIMAL(18, 8) NOT NULL,
        UsedMargin DECIMAL(18, 8) NOT NULL,
        FreeMargin DECIMAL(18, 8) NOT NULL,
        FloatingPnL DECIMAL(18, 8) NOT NULL,
        CurrProfit DECIMAL(18, 8) NOT NULL,

        CONSTRAINT PK_BackTest_AccountStateEvents
            PRIMARY KEY CLUSTERED (SimulationID ASC, CurrTimePoint ASC)
    );
END;
GO

