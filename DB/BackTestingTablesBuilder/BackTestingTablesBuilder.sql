/*
    Creates the BackTest_Deals table.

    Purpose:
    Stores closed trade/deal records generated by C++ backtest simulations.
    Each row represents a completed deal, including entry/exit time, prices,
    TP/SL levels, lot size, deal direction/type, profit, close reason,
    and the number of bars the trade was held.

    Notes:
    - The primary key is composed of SimulationID and ticket.
    - No foreign keys were defined in the source database export.
    - No production data is included.
*/

IF OBJECT_ID(N'dbo.BackTest_Deals', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BackTest_Deals
    (
        SimulationID INT NOT NULL,
        symbol NVARCHAR(32) NOT NULL,
        ticket BIGINT NOT NULL,

        openTime BIGINT NOT NULL,
        closeTime BIGINT NOT NULL,

        lotSize DECIMAL(18, 8) NOT NULL,

        openPrice DECIMAL(18, 8) NOT NULL,
        closePrice DECIMAL(18, 8) NOT NULL,
        takeProfitPrice DECIMAL(18, 8) NOT NULL,
        stopLossPrice DECIMAL(18, 8) NOT NULL,

        dealType NVARCHAR(16) NOT NULL,

        profit DECIMAL(18, 8) NOT NULL,
        profitInPips INT NOT NULL,

        closeReason NVARCHAR(32) NOT NULL,
        numOfBarsHeld INT NOT NULL,

        CONSTRAINT PK_BackTest_Deals
            PRIMARY KEY CLUSTERED (SimulationID ASC, ticket ASC)
    );
END;
GO

