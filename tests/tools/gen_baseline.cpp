// ---------------------------------------------------------------------------
// mt_gen_baseline — writes the pre-refactor scoring baseline to disk.
//
//   mt_gen_baseline [output_dir]
//
// Default output_dir is the compiled-in MTBOT_GOLDEN_DIR
// (tests/golden/baseline_v0). Regenerating these files changes what the
// regression test compares against, so it is a deliberate act: record it in
// the progress log of docs/REFACTOR_PLAN.md and explain why the numbers moved.
// ---------------------------------------------------------------------------
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>

#include "baseline_compute.h"

namespace fs = std::filesystem;

int main(int argc, char** argv) {
    fs::path outDir = (argc > 1) ? fs::path(argv[1]) : fs::path(MTBOT_GOLDEN_DIR);

    std::error_code ec;
    fs::create_directories(outDir, ec);
    if (ec) {
        std::cerr << "cannot create " << outDir.string() << ": " << ec.message() << '\n';
        return 1;
    }

    const auto artefacts = mtbot::testing::computeAllBaselineArtefacts();

    for (const auto& [name, values] : artefacts) {
        const fs::path file = outDir / (name + ".txt");
        std::ofstream out(file, std::ios::binary | std::ios::trunc);
        if (!out) {
            std::cerr << "cannot write " << file.string() << '\n';
            return 1;
        }
        out << "# MT_BOT pre-refactor baseline: " << name << '\n';
        out << "# generated by mt_gen_baseline from tests/support/baseline_fixture.h\n";
        out << "# one value per line, printed with %.9g\n";
        out << "# count " << values.size() << '\n';
        char buf[64];
        for (const float v : values) {
            std::snprintf(buf, sizeof(buf), "%.9g", static_cast<double>(v));
            out << buf << '\n';
        }
        std::cout << "wrote " << file.string() << " (" << values.size() << " values)\n";
    }

    std::cout << "baseline written to " << outDir.string() << '\n';
    return 0;
}
